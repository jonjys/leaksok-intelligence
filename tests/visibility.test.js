const assert = require('node:assert/strict');
const V = require('../src/meter-visibility.js');
const original={type:'leak',confirmedDate:'2026-09-01',note:'Bevara',hidden:false};
const hidden=V.update(original,true);
assert.equal(V.visible(hidden,'all'),false);
assert.equal(V.visible(hidden,'hidden'),true);
assert.equal(V.update(hidden,false).type,'leak');
assert.equal(V.update(hidden,false).confirmedDate,'2026-09-01');
assert.equal(original.hidden,false);
const {app,workflow,elements,stored,context}=require('./workflow-harness')();
app.state.meters=[{id:'a',category:'confirmed',address:'Test 1'},{id:'b',category:'customer_side',address:'Test 2'}];
app.state.labels.a=original;
workflow.setMetersHidden(['a'],true);
assert.equal(workflow.matchingRows().length,1);
assert.equal(workflow.matchingRows()[0].id,'b');
assert.equal(JSON.parse(stored.get('leaksok-intelligence-labels')).a.hidden,true);
elements.get('filter').value='hidden';
assert.equal(workflow.matchingRows()[0].id,'a');
workflow.setMetersHidden(['a'],false);
assert.equal(workflow.matchingRows().length,0);
elements.get('filter').value='all';
context.document.querySelectorAll = selector => selector === '#excludeFilter input:checked' ? [{value:'customer_side'}] : [];
assert.equal(workflow.matchingRows().length,1);
assert.equal(workflow.matchingRows()[0].id,'a');
assert.equal(app.state.labels.a.type,'leak');
console.log('visibility workflow tests: ok');

