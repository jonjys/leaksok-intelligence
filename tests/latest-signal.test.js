const assert = require('node:assert/strict');
const Smart = require('../src/smart-engine');
const Morning = require('../src/morning-brief');
const History = require('../src/history-comparison');
const point = (date, value) => ({readAt:new Date(date), date:new Date(new Date(date).getTime()+3600000), current:value});
const points = [point('2026-09-14T02:46',15), point('2026-09-15T06:59',125), point('2026-09-15T07:46',127)];
const change = Smart.analyzeLatestChange(points);
assert.equal(change.latest,127);
assert.equal(change.previousValue,15);
assert.equal(change.delta,112);
assert.equal(Math.round(change.percent*100),747);
assert.equal(change.observationsSinceRise,2);
assert.equal(change.firstHighAt.getTime(),points[1].readAt.getTime());
assert.equal(change.lastLowAt.getTime(),points[0].readAt.getTime());
assert.equal(change.previousEpisodes,0);
assert.deepEqual(Smart.analyzeLatestChange([...points,...points].reverse()),change,'Copies/order cannot create confirmation or alter the jump');
assert.equal(Smart.analyzeSeries(points).points,2,'Persistence still counts days');
assert.equal(Smart.analyzeLatestChange([point('2026-09-15T02:00',5),point('2026-09-15T07:00',50)]).newRise,true,'Intraday rise survives the daily floor');
assert.equal(Smart.analyzeLatestChange([point('2026-08-01',5),point('2026-09-15',50)]).newRise,false,'No fabricated fresh jump over a long gap');
assert.equal(Smart.analyzeLatestChange([point('2026-09-14',0),point('2026-09-15',50)]).percent,null);
const repeats=[5,60,5,5,62].map((v,i)=>point(`2026-09-${11+i}T05:00`,v));
assert.equal(Smart.analyzeLatestChange(repeats).previousEpisodes,1);
const maxima=[5,5,5,60].map((v,i)=>({...point(`2026-09-${12+i}T05:00`,v),max:254}));
assert.equal(Smart.analyzeLatestChange(maxima).previousEpisodes,0,'Rolling export maximum is not a dated earlier leak');
const label={type:'seasonal'};
const ranked=Smart.rankMeter({id:'a',profile:{coverage:{days:30}},reasons:[]},{id:'a',points},label);
assert.equal(ranked.category,'seasonal','Review signal preserves manual facts');
const report=Morning.build([ranked],[{exportDate:points.at(-1).date}],{a:label});
assert.equal(report.changes[0].recheck,true);
assert.equal(report.changes[0].latest,127);
assert.equal(Morning.build([{...ranked,category:'customer_side'}],[{exportDate:points.at(-1).date}]).changes.length,0);
const comparison=History.compare(points.map(p=>({...p,readingDate:p.readAt})),'previous_day');
assert.equal(comparison.latest.value,127);
assert.equal(comparison.reference.value,15);
assert.equal(History.compare(points.map(p=>({...p,readingDate:p.readAt})),'previous').reference.value,125);
const {app}=require('./workflow-harness')();
assert.equal(app.readingTimeline(points,{allReadings:true}).points.length,3);
assert.equal(app.readingTimeline(points).points.length,2);
// Slope must use the same elapsed-day coordinates in numerator and denominator.
const slope=Smart.analyzeSeries([5,6,7,8].map((v,i)=>point(`2026-09-${11+i}T05:00`,v))).normalizedSlope;
assert.ok(slope>.1 && slope<.3);
console.log('latest signal: intraday, manual review, recurrence, chronology and slope passed');
